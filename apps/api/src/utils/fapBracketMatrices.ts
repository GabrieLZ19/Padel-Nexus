export const FAP_BRACKET_PAIR_COUNTS: number[] = Object.keys(FAP_BRACKETS_BY_PAIR_COUNT).map(Number);

export function getFapBracketForPairCount(pairCount: number): readonly FapBracketMatch[] | null {
  return FAP_BRACKETS_BY_PAIR_COUNT[pairCount] ?? null;
}

export function listLeafSeeds(matches: readonly FapBracketMatch[]): string[] {
  const seeds = new Set<string>();
  for (const m of matches) {
    if (!m.a.startsWith('W')) seeds.add(m.a);
    if (!m.b.startsWith('W')) seeds.add(m.b);
  }
  return [...seeds];
}

/** Invariants: 1A/1B presentes; sin mismo-zona en cruce hoja-hoja. */
export function assertFapBracketInvariants(pairCount: number, matches: readonly FapBracketMatch[]): void {
  const leaves = listLeafSeeds(matches);
  if (!leaves.includes('1A')) throw new Error(`FAP ${pairCount}: falta 1A`);
  if (!leaves.includes('1B')) throw new Error(`FAP ${pairCount}: falta 1B`);
  if (!matches.some((m) => m.matchNo === 64)) throw new Error(`FAP ${pairCount}: falta final 64`);
  for (const m of matches) {
    if (m.a.startsWith('W') || m.b.startsWith('W')) continue;
    if (m.a[1] === m.b[1]) {
      throw new Error(`FAP ${pairCount}: misma zona en 1ª ronda ${m.a} vs ${m.b}`);
    }
  }
}

export function validateAllFapBrackets(): void {
  for (const n of FAP_BRACKET_PAIR_COUNTS) {
    assertFapBracketInvariants(n, FAP_BRACKETS_BY_PAIR_COUNT[n]);
  }
}
